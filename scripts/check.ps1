# Core-only checks; apps/desktop has separate native build/check commands.
[CmdletBinding()]
param([string]$OutputDirectory)

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
$root = Split-Path -Parent $PSScriptRoot
if (-not $OutputDirectory) {
    $OutputDirectory = Join-Path $root ("artifacts/local/checks/" + (Get-Date -Format 'yyyyMMdd-HHmmss') + '-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
}
$output = [IO.Path]::GetFullPath($OutputDirectory)
if (Test-Path -LiteralPath $output) { throw "Evidence directory already exists: $output" }
New-Item -ItemType Directory -Path $output -Force | Out-Null

function Get-SourceInventory {
    $files = @(Get-ChildItem -LiteralPath $root -File -Force)
    foreach ($directory in @('crates', 'apps', 'tools', 'docs', 'fixtures', 'prompts', 'scripts')) {
        $path = Join-Path $root $directory
        if (Test-Path -LiteralPath $path) {
            $pending = [Collections.Generic.Stack[string]]::new()
            $pending.Push($path)
            while ($pending.Count) {
                foreach ($item in (Get-ChildItem -LiteralPath $pending.Pop() -Force)) {
                    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { continue }
                    if ($item.PSIsContainer) {
                        if ($item.Name -notin @('target', 'node_modules', 'dist', '__pycache__', 'artifacts', 'gen', 'autogenerated')) { $pending.Push($item.FullName) }
                    } else { $files += $item }
                }
            }
        }
    }
    foreach ($file in ($files | Sort-Object FullName)) {
        $relative = $file.FullName.Substring($root.Length + 1).Replace('\', '/')
        if ($relative -match '(^|/)(target|node_modules|dist|__pycache__|artifacts)/') { continue }
        if ($file.Extension -notin @('.md', '.rs', '.toml', '.lock', '.json', '.txt', '.py', '.sh', '.ps1', '.ts', '.js', '.svelte', '.html', '.css', '.png', '.ico', '.svg') -and
            $file.Name -notin @('.gitignore', '.editorconfig', 'LICENSE', 'SHA256SUMS')) { continue }
        "$( (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant())  $relative"
    }
}

$checks = @(
    [ordered]@{ name = 'format'; command = 'cargo fmt --all --check'; args = @('fmt', '--all', '--check'); result = 'NOT RUN'; exit_code = $null },
    [ordered]@{ name = 'test'; command = 'cargo test -p omniterm-core --all-targets --locked --offline'; args = @('test', '-p', 'omniterm-core', '--all-targets', '--locked', '--offline'); result = 'NOT RUN'; exit_code = $null },
    [ordered]@{ name = 'clippy'; command = 'cargo clippy -p omniterm-core --all-targets --locked --offline -- -D warnings'; args = @('clippy', '-p', 'omniterm-core', '--all-targets', '--locked', '--offline', '--', '-D', 'warnings'); result = 'NOT RUN'; exit_code = $null },
    [ordered]@{ name = 'demo'; command = 'cargo run -p omniterm-core --example layout_demo --locked --offline'; args = @('run', '-p', 'omniterm-core', '--example', 'layout_demo', '--locked', '--offline'); result = 'NOT RUN'; exit_code = $null }
)
$record = [ordered]@{
    schema_version = 1
    started_utc = [DateTime]::UtcNow.ToString('o')
    finished_utc = $null
    result = 'BLOCKED'
    error = $null
    environment = [ordered]@{
        os = [Environment]::OSVersion.VersionString
        architecture = $env:PROCESSOR_ARCHITECTURE
        powershell = $PSVersionTable.PSVersion.ToString()
        working_directory = $root
        cargo = $null
        rustc = $null
    }
    source = [ordered]@{ scope = 'root files + crates/apps/tools/docs/fixtures/prompts/scripts; source extensions only; generated/dependency trees excluded'; manifest = 'source.sha256'; sha256 = $null }
    git = [ordered]@{ result = 'UNAVAILABLE'; head = $null; status = $null; diagnostic = $null }
    checks = $checks
    limits = @('Core model only; native UI, PTY, human evaluation and performance NOT RUN.')
}
$savedAutoInstall = $env:RUSTUP_AUTO_INSTALL
$exitCode = 1
Push-Location -LiteralPath $root
try {
    # Never download a missing pinned toolchain as a side effect of checking.
    $env:RUSTUP_AUTO_INSTALL = '0'
    $inventory = @(Get-SourceInventory)
    [IO.File]::WriteAllLines((Join-Path $output 'source.sha256'), [string[]]$inventory)
    $record.source.sha256 = (Get-FileHash -LiteralPath "$output/source.sha256" -Algorithm SHA256).Hash.ToLowerInvariant()
    if (Get-Command git -CommandType Application -ErrorAction SilentlyContinue) {
        $head = @(& git rev-parse HEAD 2>&1)
        $gitExit = $LASTEXITCODE
        $status = @(& git status --short --untracked-files=all 2>&1)
        if ($gitExit -eq 0 -and $LASTEXITCODE -eq 0) {
            $record.git.result = 'RECORDED'
            $record.git.head = $head -join "`n"
            $record.git.status = $status -join "`n"
        } else { $record.git.diagnostic = ($head + $status) -join "`n" }
    } else { $record.git.diagnostic = 'git unavailable; source.sha256 includes untracked source.' }
    foreach ($tool in @('cargo', 'rustc')) {
        if (-not (Get-Command $tool -CommandType Application -ErrorAction SilentlyContinue)) { throw "Required tool unavailable: $tool" }
        $version = @(& $tool --version 2>&1)
        if ($LASTEXITCODE -ne 0) { throw "$tool --version failed: $($version -join ' ')" }
        $record.environment[$tool] = $version -join "`n"
    }
    $record.result = 'PASS'
    foreach ($check in $checks) {
        Write-Host "RUN $($check.name): $($check.command)"
        $log = Join-Path $output ($check.name + '.txt')
        $check.command | Out-File -LiteralPath $log -Encoding utf8
        $arguments = $check.args
        & cargo @arguments 2>&1 | ForEach-Object {
            $line = $_.ToString()
            $line | Out-File -LiteralPath $log -Encoding utf8 -Append
            Write-Host $line
        }
        $check.exit_code = $LASTEXITCODE
        $check.result = if ($LASTEXITCODE -eq 0) { 'PASS' } else { 'FAIL' }
        Write-Host "$($check.result): $($check.name) (exit $($check.exit_code))"
        if ($check.result -eq 'FAIL') { $record.result = 'FAIL'; break }
    }
    if (($inventory -join "`n") -ne (@(Get-SourceInventory) -join "`n")) {
        $record.result = 'FAIL'
        $record.error = 'Source changed during checks; rerun on the final source.'
        Write-Host "FAIL: $($record.error)"
    }
    if ($record.result -eq 'PASS') { $exitCode = 0 }
} catch {
    $record.error = $_.Exception.Message
    $record.result = if ($record.result -eq 'BLOCKED') { 'BLOCKED' } else { 'FAIL' }
    Write-Host "$($record.result): $($record.error)"
} finally {
    $env:RUSTUP_AUTO_INSTALL = $savedAutoInstall
    Pop-Location
    $record.finished_utc = [DateTime]::UtcNow.ToString('o')
    $record | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath "$output/run.json" -Encoding utf8
    Write-Host "$($record.result): evidence $output/run.json"
}
exit $exitCode
